def test_build_tables_writes_one_file_per_spec(config: Config) -> None:
    build_index(
        config,
        make_record("R1", metrics={"LaECE0": 12.0}),
        make_record("R2", seed=1, metrics={"LaECE0": 13.0}),
        make_record("R3", factors={"detector": "detr"}, metrics={"LaECE0": 20.0}),
    )
    write(config.root, "configs/tables/main.toml", SPEC)
    results = build_tables(config)
    target = config.path("tables_dir") / "main.tex"
    assert results == [TableResult(target, True)]
    assert body(target.read_text("utf-8")) == [
        "atss & \\qcalval{agg:mean:LaECE0:R1+R2}{12.50} \\\\",
        "detr & \\qcalval{run:R3:LaECE0}{20.00} \\\\",
    ]


def test_build_tables_is_idempotent(config: Config) -> None:
    build_index(config, make_record("R1"))
