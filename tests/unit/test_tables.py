def test_load_specs_reads_every_field(config: Config) -> None:
    text = """
    [[table]]
    name = "h1"
    caption = "LaECE$_0$ before and after PTQ"
    label = "tab:h1"
    rows = ["detector", "factor.precision"]
    row_headers = ["Detector", "Precision"]
    status = ["ok", "failed"]
    alignment = "llrr"

    [table.filter]
    target = "trt_jetson"
    threshold_regime = ["reuse_fp32"]

    [[table.columns]]
    metric = "LaECE0"
    agg = "median"
    digits = 3
    header = "LaECE$_0$"

    [[table.columns]]
    metric = "AP"
    """
    (loaded,) = specs_from(config, textwrap.dedent(text))
    assert loaded == TableSpec(
        name="h1",
        rows=("factor.detector", "factor.precision"),
        columns=(
            ColumnSpec("LaECE0", "median", 3, "LaECE$_0$"),
            ColumnSpec("AP", "mean", 2, "AP"),
        ),
        row_headers=("Detector", "Precision"),
        caption="LaECE$_0$ before and after PTQ",
        label="tab:h1",
        filters={"factor.target": "trt_jetson", "factor.threshold_regime": ["reuse_fp32"]},
        statuses=("ok", "failed"),
        alignment="llrr",
    )


