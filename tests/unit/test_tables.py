HEADER = "% Generated by `qcal registry tables` from the run index. Do not edit by hand."
SPEC = """
[[table]]
name = "main"
rows = ["detector"]

[[table.columns]]
metric = "LaECE0"
"""


def row(
    run_id: str,
    *,
    detector: str = "atss",
    precision: str = "fp32",
    status: str = "ok",
    supersedes: str = "",
    cell_id: str = "C-a",
    seed: str | None = None,
    **metrics: Any,
) -> dict[str, str]:
    data = {
        "run_id": run_id,
        "cell_id": cell_id,
        "seed": run_id if seed is None else seed,  # distinct by default: one run per seed
        "status": status,
        "supersedes": supersedes,
        "factor.detector": detector,
        "factor.precision": precision,
    }
    data.update({f"metric.{name}": render_value(value) for name, value in metrics.items()})
    return data


def spec(
    *columns: ColumnSpec,
    rows: Sequence[str] = ("factor.detector",),
    statuses: Sequence[str] = ("ok",),
    **fields: Any,
) -> TableSpec:
    return TableSpec(
        name="t",
        rows=tuple(rows),
        columns=columns or (ColumnSpec("AP", "mean", 2, "AP"),),
        statuses=tuple(statuses),
        **fields,
    )


def body(text: str) -> list[str]:
    """The data rows of a rendered table (between the header rule and the closing rule)."""
    lines = text.splitlines()
    start = next(i for i, line in enumerate(lines) if line.startswith("\\begin{tabular}"))
    end = lines.index("\\end{tabular}")
    return lines[start + 4 : end - 1]


def specs_from(config: Config, text: str, name: str = "main.toml") -> list[TableSpec]:
    write(config.root, f"configs/tables/{name}", text)
    return load_specs(config)


def build_index(config: Config, *records: RunRecord) -> None:
    store = RegistryStore(config.path("registry_dir"))
    for record in records:
        store.write(record)
    write_index(config, store)


